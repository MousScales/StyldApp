#!/usr/bin/env node
/**
 * Upload local images/ files as style cover photos for Maya (mageniang06@gmail.com)
 * and upsert styld_site_records style_cover_image rows.
 *
 * Usage: node scripts/seed-maya-style-covers.mjs
 */

import { execSync } from 'node:child_process';
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const USER_ID = '091b8094-a603-4e7a-aee3-8cb380c83913';

/** styleId -> local filename under images/ */
const STYLE_IMAGES = {
  'studio-box-braids': 'knotless-box-braids-1.jpg',
  'studio-boho-box-braids': 'boho-box-braids-1.jpg',
  'studio-jumbo-box-braids': 'jumbo-box-braids-1.jpg',
  'studio-fulani-braids': 'FulaniBraids 1.png',
  'studio-lemonade-braids': 'LemonadeBraids 1.jpg',
  'studio-stitch-braids': 'StitchBraids 1.jpg',
  'studio-tribal-braids': 'tribal-braids-1.jpg',
  'studio-goddess-braids': 'GoddessBraids 1.jpg',
  'studio-cornrows': 'cornrows-1.jpg',
  'studio-senegalese-twists': 'SenegaleaseTwists 1.jpg',
  'studio-passion-twists': 'PassionTwist 1.jpg',
  'studio-marley-twists': 'MarleyTwists 1.jpg',
  'studio-two-strand-twists': 'two-strand-twists-1.png',
  'studio-starter-locs': 'starter-locs-1.png',
  'studio-loc-retwist': 'locs-retwist-1.png',
  'studio-loc-retwist-2-strand': 'lock-retwist-2-strands-1.png',
  'studio-loc-retwist-barrel': 'locs-retwist-barrel-1.png',
  'studio-weave-install': 'weave-1.jpg',
};

function extFor(fileName) {
  const ext = path.extname(fileName).toLowerCase();
  return ext || '.jpg';
}

function quote(value) {
  if (!/[\s"]/.test(value)) return value;
  return `"${value.replace(/"/g, '\\"')}"`;
}

function run(cmd) {
  execSync(cmd, { cwd: ROOT, stdio: 'inherit', shell: true, windowsHide: true });
}

function runStorageCp(localRelativePath, remotePath) {
  try {
    run(`npx supabase storage rm --linked --experimental --yes ${quote(remotePath)}`);
  } catch {
    // File may not exist yet — safe to continue.
  }
  run(
    `npx supabase storage cp --linked --experimental --yes ${quote(localRelativePath)} ${quote(remotePath)}`,
  );
}

function runDbQuery(sqlRelativePath) {
  run(`npx supabase db query --linked --yes --file ${quote(sqlRelativePath)}`);
}

const uploads = [];

for (const [styleId, fileName] of Object.entries(STYLE_IMAGES)) {
  const localRelativePath = `images/${fileName}`.replace(/\\/g, '/');
  const localPath = path.join(ROOT, localRelativePath);
  if (!existsSync(localPath)) {
    console.error(`Missing image: ${localPath}`);
    process.exit(1);
  }

  const coverName = `cover${extFor(fileName)}`;
  const storagePath = `${USER_ID}/${styleId}/${coverName}`;
  const remote = `ss:///style-covers/${storagePath}`;

  console.log(`\n→ ${styleId}`);
  console.log(`  ${fileName} → ${storagePath}`);

  runStorageCp(localRelativePath, remote);

  uploads.push({ styleId, storagePath });
}

const sqlValues = uploads
  .map(
    ({ styleId, storagePath }) =>
      `  ('${USER_ID}', 'style_cover_image', '${styleId}', jsonb_build_object('storage_path', '${storagePath}'))`,
  )
  .join(',\n');

const sql = `-- Auto-generated by scripts/seed-maya-style-covers.mjs
INSERT INTO public.styld_site_records (user_id, record_type, record_key, data)
VALUES
${sqlValues}
ON CONFLICT (user_id, record_key) WHERE record_type = 'style_cover_image'
DO UPDATE SET
  data = EXCLUDED.data,
  updated_at = now();
`;

const sqlPath = path.join('scripts', 'seed-maya-style-covers.generated.sql');
writeFileSync(path.join(ROOT, sqlPath), sql, 'utf8');

console.log(`\nApplying ${uploads.length} style_cover_image records…`);
runDbQuery(sqlPath);

console.log('\nDone — Maya style cover images are live.');
